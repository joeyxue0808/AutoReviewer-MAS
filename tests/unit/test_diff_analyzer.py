# ─────────────────────────────────────────────

class TestSplitByFile:
    def test_splits_correctly(self, analyzer, sample_diff_multi):
        parts = analyzer._split_by_file(sample_diff_multi)
        assert len(parts) == 2
        paths = [p[0] for p in parts]
        assert "src/main.py" in paths
        assert "lib/utils.go" in paths

    def test_single_file(self, analyzer, sample_diff_go):
        parts = analyzer._split_by_file(sample_diff_go)
        assert len(parts) == 2  # 两个文件


