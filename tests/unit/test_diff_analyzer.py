# ─────────────────────────────────────────────

class TestIsAutoGenerated:
    def test_lock_files(self, analyzer):
        assert analyzer._is_auto_generated("package-lock.json")
        assert analyzer._is_auto_generated("go.sum")
        assert analyzer._is_auto_generated("yarn.lock")

    def test_vendor_dirs(self, analyzer):
        assert analyzer._is_auto_generated("vendor/github.com/foo/bar.go")
        assert analyzer._is_auto_generated("node_modules/lodash/index.js")

    def test_normal_files(self, analyzer):
        assert not analyzer._is_auto_generated("src/main.py")
        assert not analyzer._is_auto_generated("cmd/server/main.go")
